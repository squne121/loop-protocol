export function buildManifest(options) {
  const repo = options.repo
  const targetType = normalizeTargetType(options.targetType)
  const targetNumber = normalizePositiveInteger(options.targetNumber, 'retro_live_verification.target_number')
  const parentIssue = normalizePositiveInteger(options.parentIssue, 'retro_live_verification.parent_issue')
  const issueNumber = normalizePositiveInteger(options.issueNumber, 'retro_live_verification.issue_number')
  const expectedDigest = normalizeSha256PrefixedDigest(options.expectedDigest, 'retro_live_verification.expected_digest')
  const expectedPayloadDigest = normalizeSha256PrefixedDigest(options.expectedPayloadDigest, 'retro_live_verification.expected_payload_digest')
  const expectedMatchedCommentCount = normalizeNonNegativeInteger(options.expectedMatchedCommentCount, 'retro_live_verification.expected_matched_comment_count')
  const reviewedHeadSha = normalizeCommitSha(options.reviewedHeadSha, 'retro_live_verification.reviewed_head_sha')
  const selectedReviewId = options.selectedReviewId === undefined || options.selectedReviewId === null
    ? null
    : normalizePositiveInteger(options.selectedReviewId, 'retro_live_verification.selected_review_id')
  const trustedActorAllowlist = normalizeTrustedActorAllowlist(options.trustedActor)
  const trustedActorIdAllowlist = normalizeTrustedActorIdAllowlist(options.trustedActorId)
  const expectedPreviousDigest = options.expectedPreviousDigest === undefined || options.expectedPreviousDigest === null || options.expectedPreviousDigest === ''
    ? null
    : normalizeSha256Hex(options.expectedPreviousDigest, 'retro_live_verification.expected_previous_digest')
  const selectedReviewCommentId = options.selectedReviewCommentId === undefined || options.selectedReviewCommentId === null
    ? null
    : normalizePositiveInteger(options.selectedReviewCommentId, 'retro_live_verification.selected_review_comment_id')
  const selectedReviewThreadNodeId = options.selectedReviewThreadNodeId === undefined || options.selectedReviewThreadNodeId === null || options.selectedReviewThreadNodeId === ''
    ? null
    : String(options.selectedReviewThreadNodeId)

  const contextAssertions = {
    repo,
    target_type: targetType,
    target_number: targetNumber,
    parent_issue: parentIssue,
    marker_comment_url: options.markerCommentUrl,
    expected_digest: expectedDigest,
    expected_payload_digest: expectedPayloadDigest,
    expected_matched_comment_count: expectedMatchedCommentCount,
  }
  // Issue #1415 AC5-7 fields are additive/optional: only included in the
  // digested payload when the caller actually supplies a value, so a v2
  // caller that never passes --selected-review-comment-id / --selected-
  // review-thread-node-id reproduces a byte-identical prReviewBinding shape
  // (and therefore the same canonical-json-v1 body_digest) as before this
  // change -- no existing fixture/manifest digest constant needs migration.
  const prReviewBinding = {
    review_artifact_ref: options.reviewArtifactRef,
    reviewed_head_sha: reviewedHeadSha,
    selected_review_id: selectedReviewId,
    ...(selectedReviewCommentId !== null ? { selected_review_comment_id: selectedReviewCommentId } : {}),
    ...(selectedReviewThreadNodeId !== null ? { selected_review_thread_node_id: selectedReviewThreadNodeId } : {}),
  }
  const ownershipMarker = buildOwnershipMarker({ repo, issueNumber })
  const { bodyDigest } = computeCanonicalCommentBody({ contextAssertions, prReviewBinding, ownershipMarker })

  return {
    schema: SCHEMA,
    context_assertions: contextAssertions,
    pr_review_binding: prReviewBinding,
    execution_boundary: {
      mode: 'generate',
      allowed_paths: [...RETRO_LIVE_VERIFICATION_ALLOWED_PATHS],
      trusted_actor_allowlist: trustedActorAllowlist,
      ...(trustedActorIdAllowlist !== null ? { trusted_actor_id_allowlist: trustedActorIdAllowlist } : {}),
    },
    canonical_comment: {
      repo,
      issue_number: issueNumber,
      ownership_marker: ownershipMarker,
      body_digest: bodyDigest,
      expected_previous_digest: expectedPreviousDigest,
    },
    runtime_provenance: {
      generated_at: new Date().toISOString(),
      generator_commit: resolveGeneratorCommit(),
      generator_version: GENERATOR_VERSION,
      // Issue #1415 AC13 (additive, optional): not part of the digested
      // canonical-comment payload (only context_assertions/pr_review_binding
      // are), so populating these unconditionally cannot change body_digest.
      ...collectExtendedRuntimeProvenance({ githubApiVersion: options.githubApiVersion }),
    },
    canonicalization_profile: {
      algorithm: 'canonical-json-v1',
      digest_encoding: 'sha256-hex',
    },
  }
}

// Issue #1415 P0-3 fix_delta: CLI option spec for the `--schema-version v3`
// dual-target generation branch. Each target's flat comment-url/digest/
// status fields are supplied as a JSON file (per-field CLI flags would mean
// ~14 required flags per target); the generator's job is limited to
// structural assembly + schema validation + execution/safety/readback
// synthesis, not re-deriving any of those live URLs/digests itself (those
// come from the operator-reviewed per-target inputs, same non-circularity
// contract as the v2 branch).
const CLI_OPTION_SPEC_V3 = {
  '--schema-version': { key: 'schemaVersion', required: true },
  '--repo': { key: 'repo', required: true },
  '--parent-issue': { key: 'parentIssue', required: true },
  '--issue-target-json': { key: 'issueTargetJson', required: true },
  '--pull-request-target-json': { key: 'pullRequestTargetJson', required: true },
  '--evidence-mode': { key: 'evidenceMode' },
  '--resolver-commit': { key: 'resolverCommit' },
  '--github-connector-only-session-declared': { key: 'githubConnectorOnlySessionDeclared' },
  '--out': { key: 'out', required: true },
}

function readJsonFileSync(path, code) {
  let raw
  try {
    raw = readFileSync(resolvePath(process.cwd(), path), 'utf-8')
  } catch (error) {
    throw usageError(code, `failed to read ${path}: ${error?.message ?? 'unknown error'}`)
  }
  try {
    return JSON.parse(raw)
  } catch (error) {
    throw usageError(code, `${path} is not valid JSON: ${error?.message ?? 'parse error'}`)
  }
}

function normalizeBooleanFlag(value, fallback) {
  if (value === undefined || value === null || value === '') {
    return fallback
  }
  if (value === 'true') return true
  if (value === 'false') return false
  throw usageError('retro_live_verification_v3.boolean_flag_invalid', `expected "true" or "false", got: ${value}`)
}

/**
 * Issue #1415 P0-3 fix_delta: assembles a `retro_live_verification/v3`
 * dual-target bundle from two already-collected per-target JSON objects
 * (matching the schema's `commonTargetFields`/`issueTarget`/
 * `pullRequestTarget` `$defs`) plus bundle-level execution/safety/readback
 * metadata. This function performs no live GitHub I/O and re-derives
 * nothing from the target objects it is handed -- it is a pure structural
 * composition + schema-validation step, same non-circularity posture as
 * v2's buildManifest(). `command_args_digest` binds the exact CLI argv used
 * to produce this bundle (not the target payload contents), mirroring the
 * v2 manifest's existing `runtime_provenance` pattern of recording how a
 * value was produced rather than re-asserting it.
 */
export function buildDualTargetManifest(options) {
  const repo = options.repo
  const parentIssue = normalizePositiveInteger(options.parentIssue, 'retro_live_verification_v3.parent_issue')
  const issueTarget = readJsonFileSync(options.issueTargetJson, 'retro_live_verification_v3.issue_target_json')
  const pullRequestTarget = readJsonFileSync(options.pullRequestTargetJson, 'retro_live_verification_v3.pull_request_target_json')
  const evidenceMode = options.evidenceMode === undefined || options.evidenceMode === null || options.evidenceMode === ''
    ? 'synthetic_route_proof'
    : options.evidenceMode
  const resolverCommit = options.resolverCommit === undefined || options.resolverCommit === null || options.resolverCommit === ''
    ? resolveGeneratorCommit()
    : normalizeCommitSha(options.resolverCommit, 'retro_live_verification_v3.resolver_commit')
  const githubConnectorOnlySessionDeclared = normalizeBooleanFlag(options.githubConnectorOnlySessionDeclared, false)

  const argvForDigest = { repo, parentIssue, issueTarget, pullRequestTarget, evidenceMode }
  const commandArgsDigest = `sha256:${sha256Hex(canonicalJsonStringify(argvForDigest))}`

  return {
    schema: DUAL_TARGET_SCHEMA,
    repo,
    parent_issue: parentIssue,
    evidence_mode: evidenceMode,
    issue_target: issueTarget,
    pull_request_target: pullRequestTarget,
    execution: {
      checked_at: new Date().toISOString(),
      resolver_commit: resolverCommit,
      command_args_digest: commandArgsDigest,
      github_connector_only_session_declared: githubConnectorOnlySessionDeclared,
    },
    safety: {
      raw_values_emitted: false,
      forbidden_fields_scan: 'pass',
    },
    readback: {
      canonical_comment_count: 1,
      digest_revalidation: 'pass',
      duplicate_count: 0,
    },
  }
}

async function runDualTargetCli(rawArgs) {
  const options = parseArgs(rawArgs, CLI_OPTION_SPEC_V3)
  const manifest = buildDualTargetManifest(options)
  const validation = await validateDualTargetBundleWithAjv(manifest)
  if (!validation.valid) {
    process.stdout.write(`${JSON.stringify({
      schema: DUAL_TARGET_SCHEMA,
      status: 'error',
      error_code: 'retro_live_verification_v3.manifest_schema_invalid',
      errors: validation.errors,
    })}\n`)
    process.exitCode = 1
    return
  }
  if (options.out === '-') {
    process.stdout.write(`${JSON.stringify(manifest, null, 2)}\n`)
    return
  }
  const outPath = resolvePath(process.cwd(), options.out)
  await mkdir(dirname(outPath), { recursive: true })
  await writeFile(outPath, `${JSON.stringify(manifest, null, 2)}\n`, 'utf-8')
  process.stdout.write(`${JSON.stringify({ schema: DUAL_TARGET_SCHEMA, status: 'ok', out: outPath })}\n`)
}

async function runCli() {
  const rawArgs = process.argv.slice(2)
  // Issue #1415 P0-3 fix_delta: --schema-version v3 routes to the dual-target
  // branch entirely; argv without this flag never touches runDualTargetCli,
  // so the v2 default (including the zero-arg DEFAULT_GENERATE_ARGS fixture
  // fallback) is completely unaffected.
  const schemaVersionIndex = rawArgs.indexOf('--schema-version')
  if (schemaVersionIndex !== -1) {
    const schemaVersionValue = rawArgs[schemaVersionIndex + 1]
    if (schemaVersionValue === 'v3') {
      await runDualTargetCli(rawArgs)
      return
    }
    if (schemaVersionValue !== 'v2') {
      throw usageError('retro_live_verification.schema_version_invalid', `--schema-version must be v2 or v3, got: ${schemaVersionValue}`)
    }
    // --schema-version v2 is accepted as an explicit no-op marker but is not
    // part of CLI_OPTION_SPEC (the v2 branch predates this flag entirely), so
    // it is stripped before the v2 parser sees argv.
    rawArgs.splice(schemaVersionIndex, 2)
  }
  const options = parseArgs(rawArgs.length === 0 ? DEFAULT_GENERATE_ARGS : rawArgs, CLI_OPTION_SPEC)
  const manifest = buildManifest(options)
  const validation = await validateManifestWithAjv(manifest)
  if (!validation.valid) {
    process.stdout.write(`${JSON.stringify({
      schema: SCHEMA,
      status: 'error',
      error_code: 'retro_live_verification.manifest_schema_invalid',
      errors: validation.errors,
    })}\n`)
    process.exitCode = 1
    return
  }

  if (options.out === '-') {
    process.stdout.write(`${JSON.stringify(manifest, null, 2)}\n`)
    return
  }
  const outPath = resolvePath(process.cwd(), options.out)
  await mkdir(dirname(outPath), { recursive: true })
  await writeFile(outPath, `${JSON.stringify(manifest, null, 2)}\n`, 'utf-8')
  process.stdout.write(`${JSON.stringify({ schema: SCHEMA, status: 'ok', out: outPath })}\n`)
}

const isDirectExecution = process.argv[1] === fileURLToPath(import.meta.url)
if (isDirectExecution) {
  runCli().catch((error) => {
    const isCliError = error instanceof CliError
    process.stdout.write(`${JSON.stringify({
      schema: SCHEMA,
      status: 'error',
      error_code: isCliError ? error.code : 'retro_live_verification.unexpected_error',
      error_message: error?.message ?? 'unexpected runtime failure',
    })}\n`)
    process.exitCode = isCliError ? error.exitCode : 2
  })
}
